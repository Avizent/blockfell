const PX = 128;
const glyphs = [
  new opentype.Glyph({ name: '.notdef', unicode: 0, advanceWidth: 6 * PX, path: new opentype.Path() }),
];

for (const [ch, rows] of Object.entries(G)) {
  const p = new opentype.Path();
  let w = 0;
  rows.forEach((row, r) => {
    w = Math.max(w, row.length);
    // merge horizontal runs into rectangles (fewer contours, identical rendering)
    let c = 0;
    while (c < row.length) {
      if (row[c] !== '#') { c++; continue; }
      let e = c;
      while (e < row.length && row[e] === '#') e++;
      const x0 = c * PX, x1 = e * PX;
      const yTop = (7 - r) * PX, yBot = (6 - r) * PX;
      // clockwise outer contour (TrueType/CFF nonzero)
      p.moveTo(x0, yBot); p.lineTo(x0, yTop); p.lineTo(x1, yTop); p.lineTo(x1, yBot); p.close();
      c = e;
    }
  });
  const adv = ch === ' ' ? 4 * PX : (w + 1) * PX;
  glyphs.push(new opentype.Glyph({
    name: 'g' + ch.codePointAt(0).toString(16),
    unicode: ch.codePointAt(0),
    advanceWidth: adv,
    path: p,
  }));
}

const font = new opentype.Font({
  familyName: 'Blockfell',
  styleName: 'Regular',
  unitsPerEm: 1024,
  ascender: 7 * PX,
  descender: -1 * PX,
  glyphs,
});

const out = path.resolve('src/assets/fonts/blockfell.otf');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, Buffer.from(font.toArrayBuffer()));
console.log('wrote', out, glyphs.length, 'glyphs', fs.statSync(out).size, 'bytes');
